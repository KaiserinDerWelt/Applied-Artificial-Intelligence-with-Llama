            errores_procesamiento.append({
                "numero": numero, "texto": texto, "causa": "herramienta_no_reconocida",
                "detalle": f"El modelo pidio ejecutar una herramienta que no existe: {e}.",
                "error": repr(e),
            })
            enviar_aviso_de_error(numero)


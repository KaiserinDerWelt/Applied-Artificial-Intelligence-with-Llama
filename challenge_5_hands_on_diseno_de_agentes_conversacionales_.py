"""**2. Construye la memoria de conversación:** Crea una conversación de **Llama Stack** por número de teléfono (`client.conversations.create()`) con una memoria de respuesta."""

# Conversacion de Llama Stack por numero de telefono

conversaciones_por_numero = {}  # { numero: conversation_id }

MAX_MENSAJES_HISTORIAL = 4  # mensajes (usuario + asistente) que se conservan por numero

def obtener_conversacion(numero):
    if numero not in conversaciones_por_numero:
        conversacion = client.conversations.create()
        conversaciones_por_numero[numero] = conversacion.id
    return conversaciones_por_numero[numero]

def texto_de_item(item):
    # Une el texto de las partes de contenido de un mensaje guardado en Llama Stack
    partes = item.content if isinstance(item.content, list) else [item.content]
    textos = []
    for parte in partes:
        if isinstance(parte, str):
            textos.append(parte)
        elif getattr(parte, "text", None):
            textos.append(parte.text)
    return " ".join(textos)

def recortar_historial(numero):
    # Si la conversacion supera el limite, se crea una nueva conversacion
    # sembrada solo con los ultimos MAX_MENSAJES_HISTORIAL mensajes
    conv_id = conversaciones_por_numero[numero]
    items = client.conversations.items.list(conversation_id=conv_id, order="asc")
    mensajes = [item for item in items.data if getattr(item, "type", "message") == "message"]

    if len(mensajes) <= MAX_MENSAJES_HISTORIAL:
        return

    recientes = mensajes[-MAX_MENSAJES_HISTORIAL:]
    nueva_conversacion = client.conversations.create(
        items=[
            {"type": "message", "role": item.role, "content": texto_de_item(item)}
            for item in recientes
        ]
    )
    conversaciones_por_numero[numero] = nueva_conversacion.id

# Definir la funcion de generacion de respuesta con memoria

FRASES_ESCALAMIENTO = ["hablar con alguien", "hablar con una persona", "agente humano", "hablar con un veterinario"]

PALABRAS_URGENCIA = [
    "urgencia", "urgente", "emergencia", "envenen", "veneno", "sangra", "sangre",
    "convulsion", "convulsión", "no respira", "atropell", "desmay", "inconsciente",
]

MENSAJE_ESCALAMIENTO = "Claro, en un momento un miembro del equipo de la veterinaria te contacta directamente."

MENSAJE_URGENCIA = (
    "Esto parece una urgencia médica. Acude de inmediato a la clínica o llama a nuestro "
    "número de urgencias; un veterinario te atenderá en cuanto llegues."
)

SYSTEM_PROMPT = (
    "Eres el asistente de una clinica veterinaria que atiende por WhatsApp: agendas citas "
    "y resuelves dudas sobre consultas, vacunas, horarios y servicios para mascotas. "
    "Responde de forma breve (2-3 lineas) y con tono amable. "
    "No des diagnosticos ni dosis de medicamentos; recomienda una consulta con el veterinario."
)

def aplicar_regla_fija(texto_usuario):
    # La urgencia medica tiene prioridad sobre el escalamiento
    texto_low = texto_usuario.lower()
    if any(palabra in texto_low for palabra in PALABRAS_URGENCIA):
        return MENSAJE_URGENCIA
    if any(frase in texto_low for frase in FRASES_ESCALAMIENTO):
        return MENSAJE_ESCALAMIENTO
    return None

def generar_respuesta(numero, texto_usuario):
    mensaje_fijo = aplicar_regla_fija(texto_usuario)
    if mensaje_fijo:
        return mensaje_fijo

    conversation_id = obtener_conversacion(numero)
    respuesta = client.responses.create(
        model="ollama/llama3.1:8b",
        input=texto_usuario,
        conversation=conversation_id,
        instructions=SYSTEM_PROMPT,
    )
    recortar_historial(numero)  # se aplica el limite despues de guardar el nuevo turno
    return respuesta.output_text

"""**3. Agrega la regla fija y protege el procesamiento por número:**

   * Cuando el usuario pide hablar con una persona, se responde con un mensaje fijo de escalamiento.
   * Igual que en el Hands-On, usa un lock por número de teléfono para que dos mensajes seguidos del mismo usuario no disparen dos llamadas en paralelo sobre la misma conversación.
"""

# Un lock por numero de telefono, para serializar mensajes del mismo usuario

import threading

locks_por_numero = {}  # { numero: threading.Lock() }

def obtener_lock(numero):
    if numero not in locks_por_numero:
        locks_por_numero[numero] = threading.Lock()
    return locks_por_numero[numero]

# Definir funcion de procesamiento: regla fija de escalamiento o respuesta de Llama

errores_procesamiento = []

def procesar_y_responder(numero, texto):
    with obtener_lock(numero):
        try:
            mensaje_fijo = aplicar_regla_fija(texto)
            if mensaje_fijo:
                enviar_respuesta(numero, mensaje_fijo)  # urgencia o escalamiento: no pasa por Llama
            else:
                respuesta = generar_respuesta(numero, texto)
                enviar_respuesta(numero, respuesta)
        except Exception as e:
            errores_procesamiento.append({"numero": numero, "texto": texto, "error": repr(e)})

